def _create_teaching_task(cur, review_row: dict[str, str], context: dict[str, Any], *, execute: bool) -> int | None:
    entity_key = _clean(review_row.get("entity_key"))
    row = _find_task_row(entity_key, context["data"]["teaching_tasks"])
    if not row:
        context["skipped"].append(_skip(review_row, "missing parsed teaching task row"))
        return None
    schedulable = _clean(row.get("schedulable")).lower()
    exclude_reason = _clean(row.get("exclude_reason"))
    total_hours = _int_or_default(row.get("total_hours"), 0)
    if schedulable == "false":
        context["skipped"].append(_skip(review_row, f"teaching task marked unschedulable: {exclude_reason or 'no normal placement needed'}"))
        return None
    if total_hours <= 0:
        context["skipped"].append(_skip(review_row, "teaching task has no positive total_hours"))
        return None
    course = context["db"]["course"].get(row.get("course_code"))
    class_names = _split_names(row.get("class_names") or row.get("class_name"))
    class_groups = [context["db"]["class_group"].get(name) for name in class_names]
    teacher_names = _split_names(row.get("teacher_name"))
    teachers = [context["db"]["teacher"].get(name) for name in teacher_names]
    if not course or not class_groups or any(item is None for item in class_groups) or not teachers or any(item is None for item in teachers):
        context["skipped"].append(_skip(review_row, "dependencies not resolved"))
        return None
    primary_teacher_id = teachers[0]["id"]
    assistant_teacher_id = teachers[1]["id"] if len(teachers) > 1 else None
    pattern = _importable_pattern(row, total_hours)
    notes = "imported_from_schedule_excel"
    if pattern["note"]:
        notes = f"{notes}; {pattern['note']}"
    context["plan"].append({
        "action": "create:teaching_task",
        "entity_key": entity_key,
        "display_name": review_row.get("display_name"),
        "details": "创建教学任务" + ("（含课表节奏）" if pattern["sessions_per_week"] else "（节奏待人工确认）"),
    })
    if execute:
        cur.execute("""
            INSERT INTO teaching_task (course_id, primary_teacher_id, assistant_teacher_id, classroom_id, total_hours,
                                       sessions_per_week, duration_weeks, required_room_type, task_batch, notes, status)
            VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
        """, (
            course["id"], primary_teacher_id, assistant_teacher_id, None, total_hours,
            pattern["sessions_per_week"], pattern["duration_weeks"],
            row.get("required_room_type") or None, row.get("task_batch") or "DEFAULT",
            notes, ACTIVE,
        ))
        cur.execute("SELECT LAST_INSERT_ID() AS id")
        task_id = cur.fetchone()["id"]
        for class_group in class_groups:
            cur.execute("INSERT INTO teaching_task_class_group (teaching_task_id, class_group_id) VALUES (%s, %s)", (task_id, class_group["id"]))
        return task_id
    return None


def _importable_pattern(row: dict[str, str], total_hours: int) -> dict[str, Any]:
    """课表网格给出的教学节奏，只在它自洽时才写进库。

    `teaching_task` 的入口校验要求 每周次数 × 持续周数 × 每次课时 == 总课时。
    真实数据里声明课时和课表实测课时经常对不上（节假日停课、补课、课程说明本身
    就是计划值），此时不能猜：把节奏留空让引擎按课时推导，并在 notes 里写清楚
    实测值，交由人工确认。静默写入一个不自洽的 pattern 会让课时审计从一开始就错。
    """
    empty = {"sessions_per_week": None, "duration_weeks": None, "note": ""}
    sessions = _int_or_default(row.get("sessions_per_week"), 0)
    weeks = _int_or_default(row.get("duration_weeks"), 0)
    session_slots = _int_or_default(row.get("session_slots"), 0)
    observed = _int_or_default(row.get("observed_hours"), 0)
    if not sessions or not weeks or not session_slots:
        return empty
    if _clean(row.get("pattern_regular")) != "true":
        return {**empty, "note": f"课表节奏不规则(每周{sessions}次×{weeks}周, 实测{observed}课时)，待人工确认"}
    if observed != total_hours:
        return {**empty, "note": f"声明{total_hours}课时与课表实测{observed}课时不一致，节奏待人工确认"}
    if sessions * weeks * session_slots != total_hours:
        return {**empty, "note": f"课表节奏与总课时不自洽(每周{sessions}次×{weeks}周×每次{session_slots}节≠{total_hours})，待人工确认"}
    return {
        "sessions_per_week": sessions,
        "duration_weeks": weeks,
        "note": f"节奏来自课表(每周{sessions}次×{weeks}周×每次{session_slots}节)",
    }


def _default_department(context: dict[str, Any]) -> str:
    for row in context.get("data", {}).get("class_groups", {}).values():
        department = _clean(row.get("department"))
        if department:
            return department
    return "电子信息与计算机工程系"


def _find_task_row(entity_key: str, rows: list[dict[str, str]]) -> dict[str, str] | None:
    for row in rows:
        class_names = ",".join(_split_names(row.get("class_names") or row.get("class_name")))
        teacher_names = ",".join(_split_names(row.get("teacher_name")))
        key = f"{row.get('course_code')}|{class_names}|{teacher_names}"
        if key == entity_key:
            return row
    return None


def _load_db(cur) -> dict[str, dict[str, dict[str, Any]]]:
    return {
        "course": {_clean(row["code"]): row for row in _fetch(cur, "SELECT id, code, name FROM course") if _clean(row.get("code"))},
        "teacher": {_clean(row["name"]): row for row in _fetch(cur, "SELECT id, name FROM teacher") if _clean(row.get("name"))},
        "classroom": {_clean(row["name"]): row for row in _fetch(cur, "SELECT id, name FROM classroom") if _clean(row.get("name"))},
        "class_group": {_clean(row["name"]): row for row in _fetch(cur, "SELECT id, name FROM class_group") if _clean(row.get("name"))},
    }


def _fetch(cur, sql: str) -> list[dict[str, Any]]:
    cur.execute(sql)
    return list(cur.fetchall())


def _read_csv(path: Path) -> list[dict[str, str]]:
    if not path.exists():
        return []
    with path.open("r", encoding="utf-8-sig", newline="") as handle:
        return list(csv.DictReader(handle))


def _index(rows: list[dict[str, str]], key_field: str) -> dict[str, dict[str, str]]:
    return {_clean(row.get(key_field)): row for row in rows if _clean(row.get(key_field))}


def _plan(row: dict[str, str], action: str, details: str) -> dict[str, Any]:
    return {"action": action, "entity_type": row.get("entity_type"), "entity_key": row.get("entity_key"), "display_name": row.get("display_name"), "details": details}


def _skip(row: dict[str, str], reason: str) -> dict[str, Any]:
    return {"entity_type": row.get("entity_type"), "entity_key": row.get("entity_key"), "display_name": row.get("display_name"), "reason": reason}


def _counts(rows: list[dict[str, Any]], key: str) -> dict[str, int]:
    result: dict[str, int] = {}
    for row in rows:
        value = str(row.get(key) or "")
        result[value] = result.get(value, 0) + 1
    return dict(sorted(result.items()))


def _dry_id(entity_type: str, key: str) -> int:
    return -(abs(hash(f"{entity_type}:{key}")) % 1_000_000_000 + 1)


def _typed_value(value: str, field_name: str) -> Any:
    if field_name in {"required_hours", "capacity", "student_count"}:
        return _int_or_default(value, 0)
    if field_name == "credits":
        return _float_or_none(value)
    return value or None


def _int_or_default(value: Any, default: int) -> int:
    try:
        return int(float(str(value).strip()))
    except (TypeError, ValueError):
        return default


def _float_or_none(value: Any) -> float | None:
    try:
        return float(str(value).strip())
    except (TypeError, ValueError):
        return None


def _split_names(value: Any) -> list[str]:
    text = str(value or "").replace("，", ",").replace("、", ",")
    return [_clean(item) for item in text.split(",") if _clean(item)]


def _clean(value: Any) -> str:
    return str(value or "").strip()


def main() -> None:
    parser = argparse.ArgumentParser(description="Apply reviewed schedule import decisions.")
    parser.add_argument("--input-dir", required=True)
    parser.add_argument("--execute", action="store_true")
    args = parser.parse_args()
    report = apply_review(input_dir=Path(args.input_dir), execute=args.execute)
    print(json.dumps({k: v for k, v in report.items() if k not in {"planned_preview", "skipped_preview"}}, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
