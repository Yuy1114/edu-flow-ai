"""Apply human-reviewed schedule import decisions.

Input directory should contain:
- courses.csv / teachers.csv / classrooms.csv / class_groups.csv / teaching_tasks.csv
- import_review_items.csv generated by prepare_import_review.py and manually filled in `decision`

Safety:
- Dry-run by default.
- Use --execute to write database changes.
- Rows without decision are skipped.
"""

from __future__ import annotations

import argparse
import csv
import json
import os
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))
from app.db.session import connect, load_db_config  # noqa: E402

ACTIVE = "ACTIVE"
DEFAULT_TEACHER_ROLE = "TEACHER"
DEFAULT_TEACHER_PASSWORD = "123456"


def apply_review(*, input_dir: Path, execute: bool = False) -> dict[str, Any]:
    if not input_dir.exists() or not input_dir.is_dir():
        raise SystemExit(f"input-dir not found: {input_dir}")

    data = {
        "courses": _index(_read_csv(input_dir / "courses.csv"), "course_code"),
        "teachers": _index(_read_csv(input_dir / "teachers.csv"), "teacher_name"),
        "classrooms": _index(_read_csv(input_dir / "classrooms.csv"), "classroom_name"),
        "class_groups": _index(_read_csv(input_dir / "class_groups.csv"), "class_name"),
        "teaching_tasks": _read_csv(input_dir / "teaching_tasks.csv"),
        "review_items": _read_csv(input_dir / "import_review_items.csv"),
    }

    decisions = [row for row in data["review_items"] if _clean(row.get("decision"))]
    plan: list[dict[str, Any]] = []
    skipped: list[dict[str, Any]] = []

    conn = connect(load_db_config())
    try:
        with conn.cursor() as cur:
            db = _load_db(cur)
            conn.begin()
            context = {"db": db, "data": data, "plan": plan, "skipped": skipped}
            for row in decisions:
                _apply_decision(cur, row, context, execute=execute)
            if execute:
                conn.commit()
            else:
                conn.rollback()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()

    outcome = _categorize(data["review_items"], plan, skipped)
    report = {
        "status": "applied" if execute else "dry_run_ok",
        "execute": execute,
        "input_dir": str(input_dir),
        "decision_count": len(decisions),
        "planned_count": len(plan),
        "skipped_count": len(skipped),
        "outcome_counts": outcome,
        "planned_counts": _counts(plan, "action"),
        "skipped_counts": _counts(skipped, "reason"),
        "planned_preview": plan[:80],
        "skipped_preview": skipped[:80],
    }
    if execute:
        report["import_batch_id"] = _record_batch(
            input_dir=input_dir,
            data=data,
            decisions=decisions,
            outcome=outcome,
            report=report,
        )
    (input_dir / "import_apply_report.json").write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
    return report


def _categorize(review_items: list[dict[str, str]], plan: list[dict[str, Any]], skipped: list[dict[str, Any]]) -> dict[str, int]:
    """把一次导入的结果分成新增 / 更新 / 冲突 / 异常 / 跳过五类。

    冲突是复核项本身的属性（有多少字段两边不一致），另外四类是这次执行的去向。
    异常与跳过要分开：跳过是人工明确说"不动"，异常是系统没能应用（依赖没解析出来、
    字段不支持自动落库、merge 没填值），后者必须留在报告里让人看见。
    """
    explicit_skip = sum(1 for item in plan if item.get("action", "").startswith(("ignore:", "keep_db:")))
    return {
        "created": sum(1 for item in plan if item.get("action", "").startswith("create:")),
        "updated": sum(1 for item in plan if item.get("action", "").startswith("update:")),
        "conflicts": sum(1 for row in review_items if _clean(row.get("review_type")) == "conflict"),
        "anomalies": len(skipped),
        "skipped": explicit_skip,
    }


def _record_batch(
    *,
    input_dir: Path,
    data: dict[str, Any],
    decisions: list[dict[str, str]],
    outcome: dict[str, int],
    report: dict[str, Any],
) -> int | None:
    """把这次落库记进 import_batch 台账。

    台账失败不能反过来把已经提交的导入回滚掉——数据已经在库里了，
    丢掉台账行只是少了一条来源记录，谎报导入失败要糟糕得多。
    """
    task_batches = sorted({
        _clean(row.get("task_batch")) for row in data["teaching_tasks"] if _clean(row.get("task_batch"))
    })
    summary = {
        "outcome_counts": outcome,
        "planned_counts": report["planned_counts"],
        "skipped_counts": report["skipped_counts"],
        "task_batches": task_batches,
    }
    conn = connect(load_db_config())
    try:
        with conn.cursor() as cur:
            conn.begin()
            cur.execute(
                """
                INSERT INTO import_batch (source_name, source_kind, task_batch, imported_by, status,
                                          decision_count, created_count, updated_count, conflict_count,
                                          anomaly_count, skipped_count, summary_json)
                VALUES (%s, %s, %s, %s, 'APPLIED', %s, %s, %s, %s, %s, %s, %s)
                """,
                (
                    str(input_dir), "DIRECTORY",
                    task_batches[0] if task_batches else "DEFAULT",
                    os.getenv("EDU_FLOW_IMPORT_OPERATOR", "local-demo-operator"),
                    len(decisions), outcome["created"], outcome["updated"], outcome["conflicts"],
                    outcome["anomalies"], outcome["skipped"],
                    json.dumps(summary, ensure_ascii=False),
                ),
            )
            cur.execute("SELECT LAST_INSERT_ID() AS id")
            batch_id = int(cur.fetchone()["id"])
            conn.commit()
            return batch_id
    except Exception as exception:  # noqa: BLE001 - 台账写入失败不应回滚已提交的导入
        print(f"[IMPORT] 导入已落库，但 import_batch 台账写入失败: {exception}", file=sys.stderr, flush=True)
        return None
    finally:
        conn.close()


def _apply_decision(cur, row: dict[str, str], context: dict[str, Any], *, execute: bool) -> None:
    decision = _clean(row.get("decision"))
    entity_type = _clean(row.get("entity_type"))
    entity_key = _clean(row.get("entity_key"))
    review_type = _clean(row.get("review_type"))
    if decision in {"ignore", "keep_db"}:
        context["plan"].append(_plan(row, f"{decision}:{entity_type}", "不修改数据库"))
        return
    if review_type == "conflict" and decision in {"use_import", "merge"}:
        _apply_conflict_value(cur, row, context, execute=execute)
        return
    if review_type == "new_item" and decision in {"create", "create_after_dependencies"}:
        if entity_type == "course":
            _create_course(cur, entity_key, context, execute=execute)
            return
        if entity_type == "teacher":
            _create_teacher(cur, entity_key, context, execute=execute)
            return
        if entity_type == "class_group":
            _create_class_group(cur, entity_key, context, execute=execute)
            return
        if entity_type == "classroom":
            _create_classroom(cur, entity_key, context, execute=execute)
            return
        if entity_type == "teaching_task":
            _create_teaching_task(cur, row, context, execute=execute)
            return
    context["skipped"].append(_skip(row, f"unsupported decision: {decision}"))


def _apply_conflict_value(cur, row: dict[str, str], context: dict[str, Any], *, execute: bool) -> None:
    """把一个字段冲突的最终取值落库。

    use_import 采用导入值；merge 采用复核人在 merged_value 里写下的第三个值
    （例如两边都不完全对，人工给出正确的教室容量）。merge 没写值等同于没有决定，
    必须显式拒绝而不是悄悄退回导入值。
    """
    entity_type = _clean(row.get("entity_type"))
    entity_key = _clean(row.get("entity_key"))
    field_name = _clean(row.get("field_name"))
    decision = _clean(row.get("decision"))
    merged_value = _clean(row.get("merged_value"))
    if decision == "merge" and not merged_value:
        context["skipped"].append(_skip(row, "merge decision without merged_value"))
        return
    import_value = merged_value if decision == "merge" else _clean(row.get("import_value"))
    db_id = _clean(row.get("db_id"))
    sql_map = {
        ("course", "course_name"): ("course", "name"),
        ("course", "credits"): ("course", "credits"),
        ("course", "required_hours"): ("course", "required_hours"),
        ("course", "course_type"): ("course", "course_type"),
        ("course", "required_room_type"): ("course", "required_room_type"),
        ("classroom", "classroom_type"): ("classroom", "classroom_type"),
        ("classroom", "capacity"): ("classroom", "capacity"),
        ("classroom", "status"): ("classroom", "status"),
        ("class_group", "major"): ("class_group", "major"),
        ("class_group", "department"): ("class_group", "department"),
        ("class_group", "grade"): ("class_group", "grade"),
        ("class_group", "student_count"): ("class_group", "student_count"),
    }
    target = sql_map.get((entity_type, field_name))
    if not target or not db_id:
        context["skipped"].append(_skip(row, "conflict field cannot be applied automatically"))
        return
    table, column = target
    value = _typed_value(import_value, field_name)
    source = "人工合并值" if decision == "merge" else "导入值"
    context["plan"].append(_plan(row, f"update:{table}.{column}", f"{entity_key}: {column} = {value}（{source}）"))
    if execute:
        cur.execute(f"UPDATE {table} SET {column} = %s WHERE id = %s", (value, db_id))


def _create_course(cur, code: str, context: dict[str, Any], *, execute: bool) -> int | None:
    existing = context["db"]["course"].get(code)
    if existing:
        return existing["id"]
    row = context["data"]["courses"].get(code)
    if not row:
        context["skipped"].append({"entity_type": "course", "entity_key": code, "reason": "missing parsed course row"})
        return None
    values = (
        row.get("course_name"), code, _float_or_none(row.get("credits")), row.get("course_type") or "理论课",
        row.get("required_room_type") or None, _int_or_default(row.get("required_hours"), 16), row.get("raw_text") or None, ACTIVE,
    )
    context["plan"].append({"action": "create:course", "entity_key": code, "display_name": row.get("course_name"), "details": "创建课程"})
    if execute:
        cur.execute("""
            INSERT INTO course (name, code, credits, course_type, required_room_type, required_hours, description, status)
            VALUES (%s, %s, %s, %s, %s, %s, %s, %s)
        """, values)
        cur.execute("SELECT LAST_INSERT_ID() AS id")
        row_id = cur.fetchone()["id"]
    else:
        row_id = _dry_id("course", code)
    context["db"]["course"][code] = {"id": row_id, "code": code}
    return row_id


def _create_teacher(cur, name: str, context: dict[str, Any], *, execute: bool) -> int | None:
    existing = context["db"]["teacher"].get(name)
    if existing:
        return existing["id"]
    row = context["data"]["teachers"].get(name, {})
    context["plan"].append({"action": "create:teacher", "entity_key": name, "display_name": name, "details": "创建教师"})
    if execute:
        employee_no = f"IMPORT_{name}"
        cur.execute("""
            INSERT INTO teacher (employee_no, password, role, name, department, title, status)
            VALUES (%s, %s, %s, %s, %s, %s, %s)
        """, (
            employee_no,
            DEFAULT_TEACHER_PASSWORD,
            DEFAULT_TEACHER_ROLE,
            name,
            row.get("department") or _default_department(context),
            row.get("title") or None,
            ACTIVE,
        ))
        cur.execute("SELECT LAST_INSERT_ID() AS id")
        row_id = cur.fetchone()["id"]
    else:
        row_id = _dry_id("teacher", name)
    context["db"]["teacher"][name] = {"id": row_id, "name": name}
    return row_id


